function countryName(code) {
  const c = COUNTRIES.find(x => x.code === code);
  return c ? c.name : '';
}

function countryExists(code) {
  return COUNTRIES.some(c => c.code === code);
}

function citiesForCountry(code) {
  return CITY_FALLBACK[code] || [];
}

// Поиск по локальному списку: сначала совпадения с начала строки,
// потом вхождения в середину — так «Ростов» находится раньше «Новороссийска».
function matchLocalCities(query, countryCode, limit) {
  const max = limit || 10;
  const cities = citiesForCountry(countryCode || DEFAULT_COUNTRY);
  const q = (query || '').trim().toLowerCase();
  if (!q) return cities.slice(0, max);

  const starts = [];
  const contains = [];
  cities.forEach(name => {
    const low = name.toLowerCase();
    if (low.startsWith(q)) starts.push(name);
    else if (low.includes(q)) contains.push(name);
  });
  return starts.concat(contains).slice(0, max);
}
