/* ============================================================
   js/managerTools.js — раздел «Инструменты менеджера».

   Пункт меню виден только менеджеру по продажам (role !== 'admin').
   Пока это пустой контейнер под будущие инструменты: калькуляторы,
   шаблоны писем, чек-листы по клиентам и прочие помощники в работе.
   Чтобы добавить инструмент, достаточно положить его разметку в
   #managerToolsGrid в renderManagerTools().
   ============================================================ */

function renderManagerTools() {
  const main = document.getElementById('mainContent');
  if (!main) return;

  // Раздел для менеджеров: администратору он не показывается в меню,
  // но при прямом переходе получает понятный отказ.
  if (!currentUser || isAdmin()) {
    main.innerHTML = `<div class="placeholder"><h2>Доступ запрещён</h2><p>Раздел доступен менеджеру по продажам</p></div>`;
    return;
  }

  main.innerHTML = `
    <div class="tools-page">
      <div class="tools-head">
        <h1>Инструменты менеджера</h1>
        <span class="tools-badge">раздел в разработке</span>
      </div>

      <div class="tools-grid" id="managerToolsGrid">
        <div class="tools-empty">
          <h2>Здесь появятся рабочие инструменты</h2>
          <p>
            Раздел создан как контейнер под будущие помощники: калькулятор цен,
            шаблоны писем и коммерческих предложений, чек-листы по клиентам.
          </p>
        </div>
      </div>
    </div>
  `;
}
